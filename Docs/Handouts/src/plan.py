def part_table(part: int) -> Raw:
    rows = []
    for x in lessons_of(part):
        title = f"**{x['title']}**"
        if x["opt"]:
            title = J(Raw(T(title) + " " + st("opt")))
        rows.append([x["id"], title, x["concepts"], x["result"], f"{x['hours']}h"])
    return table(
        [7, 21, 35, 30, 7],
        ["강", "주제", "핵심 개념", "끝나면 보이는 것", "시간"],
        rows,
        cell_cls=["num", "", "", "", "r"],
        sum_row=["", f"{len(rows)}강", "", "", f"{hours_of(part)}h"],
    )


def part_side(part: int) -> str:
    rows = lessons_of(part)
    return f"{rows[0]['id']} 〜 {rows[-1]['id']} · {len(rows)}강 · {hours_of(part)}h"


